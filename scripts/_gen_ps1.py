import base64

T = "\t"
L = []
def a(*lines): L.extend(lines)

a("[CmdletBinding()]", "param(",
  T + '[string]$EnvironmentPath = (Join-Path $PSScriptRoot "..\CUDAPython.Dotnet.Python\bin\Release\net10.0\python-env-win-x64"),',
  T + '[string]$RuntimeId = "win-x64",',
  T + "[switch]$Upgrade",
  ")")
a("",
  '$ErrorActionPreference = "Stop"',
  'if ($RuntimeId -ne "win-x64" -and $RuntimeId -ne "linux-x64") {',
  T + 'throw "Supported RuntimeId values: win-x64, linux-x64. Got: $RuntimeId"',
  "}",
  '$manifestPath = Join-Path $PSScriptRoot "python-runtime-$RuntimeId.json"',
  "$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json",
  "")
a("function Get-Sha256Hash([string]$FilePath) {",
  T + "$stream = [System.IO.File]::OpenRead($FilePath)",
  T + "$sha256 = [System.Security.Cryptography.SHA256]::Create()",
  T + "try {",
  T + T + 'return [System.BitConverter]::ToString($sha256.ComputeHash($stream)).Replace("-", "").ToLowerInvariant()',
  T + "}",
  T + "finally {",
  T + T + "$sha256.Dispose()",
  T + T + "$stream.Dispose()",
  T + "}",
  "}",
  "")
a('if ($RuntimeId -eq "win-x64") {',
  T + 'if ($env:OS -ne "Windows_NT" -or $env:PROCESSOR_ARCHITECTURE -ne "AMD64") {',
  T + T + 'throw "The win-x64 bundled Python runtime requires Windows x64."',
  T + "}",
  "}",
  "")
a("$resolvedEnvironmentPath = [System.IO.Path]::GetFullPath($EnvironmentPath)",
  '$runtimeConfigPath = Join-Path $resolvedEnvironmentPath "runtime.json"',
  "$pythonExecutable = Join-Path $resolvedEnvironmentPath $manifest.pythonExecutable",
  "")
a("if (-not $Upgrade -and (Test-Path $runtimeConfigPath) -and (Test-Path $pythonExecutable)) {",
  T + "$currentRuntime = Get-Content -LiteralPath $runtimeConfigPath -Raw | ConvertFrom-Json",
  T + "if ($currentRuntime.pythonVersion -eq $manifest.pythonVersion -and $currentRuntime.runtimeId -eq $manifest.runtimeId) {",
  T + T + "Write-Output \"Using the existing CPython $($manifest.pythonVersion) environment at '$resolvedEnvironmentPath'.\"",
  T + T + "return",
  T + "}",
  "}",
  "")
a("$environmentParent = Split-Path -Parent $resolvedEnvironmentPath",
  '$downloadDirectory = Join-Path $env:TEMP "CUDAPython.Dotnet\downloads"',
  "$archivePath = Join-Path $downloadDirectory (Split-Path -Leaf $manifest.pythonArchiveUrl)",
  '$partialArchivePath = "$archivePath.partial"',
  '$stagingPath = "$resolvedEnvironmentPath.staging-$([guid]::NewGuid().ToString(\'N\'))"',
  '$backupPath = "$resolvedEnvironmentPath.backup-$([guid]::NewGuid().ToString(\'N\'))"',
  "")
a("New-Item -ItemType Directory -Path $environmentParent -Force | Out-Null",
  "New-Item -ItemType Directory -Path $downloadDirectory -Force | Out-Null",
  "",
  "$runtimeMetadataScript = @'")
a("import importlib.metadata", "import json", "import os", "import platform",
  "from pathlib import Path", "import sys", "",
  "prefix = Path(sys.prefix).resolve()",
  'ver = f"{sys.version_info.major}{sys.version_info.minor}"',
  'if platform.system() == "Windows":',
  '    lib = prefix / f"python{ver}.dll"',
  "else:",
  '    lib = prefix / "lib" / f"libpython{ver}.so.1.0"',
  "    if not lib.is_file():",
  '        lib = prefix / "lib" / f"libpython{ver}.so"',
  "if not lib.is_file():",
  '    raise FileNotFoundError(f"CPython shared library not found: {lib}")',
  "",
  "python_paths = []",
  "for entry in sys.path:",
  "    if not entry:",
  "        continue",
  "    resolved = Path(entry).resolve()",
  "    try:",
  "        relative = resolved.relative_to(prefix)",
  "    except ValueError:",
  "        continue",
  '    python_paths.append((Path("python") / relative).as_posix())',
  "",
  "print(json.dumps({",
  '    "pythonDllPath": (Path("python") / lib.relative_to(prefix)).as_posix(),',
  '    "pythonHome": "python",',
  '    "pythonPath": os.pathsep.join(python_paths),',
  '    "pythonVersion": ".".join(map(str, sys.version_info[:3])),',
  '    "cudaPythonVersion": importlib.metadata.version("cuda-python"),',
  '    "runtimeId": "__RUNTIME_ID__"',
  "}, indent=2))",
  "'@",
  '$runtimeMetadataScript = $runtimeMetadataScript -replace "__RUNTIME_ID__", $RuntimeId',
  "")
a("try {",
  T + "if (-not (Test-Path $archivePath) -or",
  T + T + "(Get-Sha256Hash $archivePath) -ne $manifest.pythonArchiveSha256) {",
  T + T + "if (Test-Path $archivePath) {",
  T + T + T + "Remove-Item -LiteralPath $archivePath -Force",
  T + T + "}",
  T + T + "if (Test-Path $partialArchivePath) {",
  T + T + T + "Remove-Item -LiteralPath $partialArchivePath -Force",
  T + T + "}",
  "",
  T + T + "Invoke-WebRequest -Uri $manifest.pythonArchiveUrl -OutFile $partialArchivePath",
  T + T + "$downloadHash = Get-Sha256Hash $partialArchivePath",
  T + T + "if ($downloadHash -ne $manifest.pythonArchiveSha256) {",
  T + T + T + 'throw "The downloaded CPython archive failed SHA-256 verification."',
  T + T + "}",
  "",
  T + T + "Move-Item -LiteralPath $partialArchivePath -Destination $archivePath",
  T + "}",
  "",
  T + "New-Item -ItemType Directory -Path $stagingPath | Out-Null",
  T + "& tar.exe -xzf $archivePath -C $stagingPath",
  T + "if ($LASTEXITCODE -ne 0) {",
  T + T + 'throw "Failed to extract the bundled CPython runtime."',
  T + "}",
  "",
  T + "$stagedPython = Join-Path $stagingPath $manifest.pythonExecutable",
  T + "$stagedLib = Join-Path $stagingPath $manifest.pythonSharedLibrary",
  T + "if (-not (Test-Path $stagedPython)) {",
  T + T + 'throw "The CPython archive does not contain the expected Python executable: $($manifest.pythonExecutable)"',
  T + "}",
  T + "if (-not (Test-Path $stagedLib)) {",
  T + T + 'throw "The CPython archive does not contain the expected shared library: $($manifest.pythonSharedLibrary)"',
  T + "}",
  "",
  T + '$pipCache = Join-Path $env:TEMP "CUDAPython.Dotnet\pip-cache"',
  T + "New-Item -ItemType Directory -Path $pipCache -Force | Out-Null",
  T + "& $stagedPython -m pip install --upgrade --disable-pip-version-check --no-warn-script-location --cache-dir $pipCache $manifest.cudaPythonRequirement",
  T + "if ($LASTEXITCODE -ne 0) {",
  T + T + 'throw "Failed to install the latest CPython-compatible cuda-python release."',
  T + "}",
  "",
  T + "& $stagedPython -m pip check",
  T + "if ($LASTEXITCODE -ne 0) {",
  T + T + 'throw "The bundled Python environment has dependency conflicts."',
  T + "}",
  "",
  T + "$requirements = & $stagedPython -m pip freeze --all",
  T + "if ($LASTEXITCODE -ne 0) {",
  T + T + 'throw "Failed to create the Python dependency lock file."',
  T + "}",
  T + "[System.IO.File]::WriteAllLines(",
  T + T + '(Join-Path $stagingPath "requirements.lock.txt"),',
  T + T + "[string[]]$requirements,",
  T + T + "[System.Text.UTF8Encoding]::new($false))",
  "",
  T + '$runtimeMetadataScriptPath = Join-Path $stagingPath "_write_runtime_metadata.py"',
  T + "[System.IO.File]::WriteAllText(",
  T + T + "$runtimeMetadataScriptPath,",
  T + T + "$runtimeMetadataScript,",
  T + T + "[System.Text.UTF8Encoding]::new($false))",
  "",
  T + "$runtimeMetadataLines = & $stagedPython $runtimeMetadataScriptPath",
  T + "if ($LASTEXITCODE -ne 0) {",
  T + T + 'throw "Failed to inspect the bundled Python environment."',
  T + "}",
  T + "Remove-Item -LiteralPath $runtimeMetadataScriptPath -Force",
  T + "$runtimeMetadataJson = $runtimeMetadataLines -join [Environment]::NewLine",
  T + "[System.IO.File]::WriteAllText(",
  T + T + '(Join-Path $stagingPath "runtime.json"),',
  T + T + "$runtimeMetadataJson,",
  T + T + "[System.Text.UTF8Encoding]::new($false))",
  T + 'Copy-Item -LiteralPath $manifestPath -Destination (Join-Path $stagingPath "provisioning.json")',
  "",
  T + "if (Test-Path $resolvedEnvironmentPath) {",
  T + T + "Move-Item -LiteralPath $resolvedEnvironmentPath -Destination $backupPath",
  T + "}",
  T + "try {",
  T + T + "Move-Item -LiteralPath $stagingPath -Destination $resolvedEnvironmentPath",
  T + "}",
  T + "catch {",
  T + T + "if (Test-Path $backupPath) {",
  T + T + T + "Move-Item -LiteralPath $backupPath -Destination $resolvedEnvironmentPath",
  T + T + "}",
  T + T + "throw",
  T + "}",
  "",
  T + "if (Test-Path $backupPath) {",
  T + T + "Remove-Item -LiteralPath $backupPath -Recurse -Force",
  T + "}",
  "",
  T + "Write-Output \"Bundled CPython $($manifest.pythonVersion) and cuda-python $((Get-Content -LiteralPath $runtimeConfigPath -Raw | ConvertFrom-Json).cudaPythonVersion) at '$resolvedEnvironmentPath'.\"",
  "}",
  "finally {",
  T + "if (Test-Path $partialArchivePath) {",
  T + T + "Remove-Item -LiteralPath $partialArchivePath -Force",
  T + "}",
  T + "if (Test-Path $stagingPath) {",
  T + T + "Remove-Item -LiteralPath $stagingPath -Recurse -Force",
  T + "}",
  "}")

out = "\r\n".join(L) + "\r\n"
with open("C:/Users/marce/source/repos/CUDAPython.Dotnet/scripts/_ps1_b64.txt", "w") as f:
    f.write(base64.b64encode(out.encode("utf-8")).decode("ascii"))
print(f"OK {len(out)} chars, {len(L)} lines")